
# 1-нұсқа. Кітапхана
genres = [
    "Роман", "Фантастика", "Детектив",
    "Роман", "Поэзия", "Фантастика",
    "Тарихи", "Роман", "Детектив",
    "Фантастика", "Комедия", "Роман"
]

books = [
    {"атауы": "Абай жолы", "жанры": "Роман", "жылы": 1942},
    {"атауы": "Марсианин", "жанры": "Фантастика", "жылы": 2011},
    {"атауы": "Шерлок Холмс", "жанры": "Детектив", "жылы": 2022},
    {"атауы": "Үш дене туралы мәселе", "жанры": "Фантастика", "жылы": 2021},
    {"атауы": "Көшпенділер", "жанры": "Тарихи", "жылы": 2023}
]

while True:
    print("\n===== КІТАПХАНА =====")
    print("1. Бірегей жанрларды көру")
    print("2. Жанрлардың жиілігін көру")
    print("3. 2020 жылдан кейінгі кітаптарды көру")
    print("4. Барлық кітаптарды көру")
    print("0. Шығу")

    choice = input("\nТаңдауыңызды енгізіңіз: ")

    # 1. Бірегей жанрлар
    if choice == "1":
        unique_genres = set(genres)

        print("\nБірегей жанрлар:")
        for genre in unique_genres:
            print(genre)

        print("Қайталанатын элементтер саны:",
              len(genres) - len(unique_genres))

    # 2. Жанрлардың жиілігі
    elif choice == "2":
        frequency = {}

        for genre in genres:
            if genre in frequency:
                frequency[genre] += 1
            else:
                frequency[genre] = 1

        print("\nЖанрлардың жиілігі:")
        for genre, count in frequency.items():
            print(genre, "-", count)

    # 3. 2020 жылдан кейінгі кітаптар
    elif choice == "3":
        print("\n2020 жылдан кейінгі кітаптар:")

        for book in books:
            if book["жылы"] > 2020:
                print(book["атауы"], "-", book["жанры"],
                      "-", book["жылы"])

    # 4. Барлық кітаптар
    elif choice == "4":
        print("\nБарлық кітаптар:")

        for book in books:
            print(book)

    # 0. Бағдарламадан шығу
    elif choice == "0":
        print("Бағдарлама аяқталды.")
        break

    else:
        print("Қате таңдау! Қайта енгізіңіз.")
